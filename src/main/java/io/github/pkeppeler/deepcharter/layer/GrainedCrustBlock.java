package io.github.pkeppeler.deepcharter.layer;

import io.github.pkeppeler.deepcharter.scanner.LoadedBlocks;
import java.util.ArrayList;
import java.util.List;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.core.particles.ParticleTypes;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.sounds.SoundEvents;
import net.minecraft.sounds.SoundSource;
import net.minecraft.util.RandomSource;
import net.minecraft.world.level.LevelReader;
import net.minecraft.world.level.ScheduledTickAccess;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.LiquidBlock;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.StateDefinition;
import net.minecraft.world.level.block.state.properties.BooleanProperty;

/**
 * The grained crust (#746, ADR 0060). Two of its rules live in the block, because they answer a change next to it:
 *
 * <ul>
 *   <li>A block placed against it crumbles on the next pulse and drops nothing; a fluid that reaches it is absorbed.
 *   <li>The block cannot tell a placed block from the rock the world generated by what the block is, so it is told by the change: a
 *       neighbour that changes into something solid, or a fluid, sets that side's {@code changed} flag. The tick that follows reads only
 *       the flagged sides, so the layer's own rock beside it is never touched and a block of the same kind a player places is.
 *       The flags are the block's state and nothing else: every state looks the same.
 * </ul>
 *
 * A flagged side is looked at every tick until it is dealt with: a fluid on the next tick, a placed block on the tick of the next pulse.
 * (A scheduled tick that is already set cannot be moved earlier, so a wait for the pulse would hold a fluid back as well.)
 */
public final class GrainedCrustBlock extends Block {
    private static final BooleanProperty CHANGED_DOWN = BooleanProperty.create("changed_down");
    private static final BooleanProperty CHANGED_UP = BooleanProperty.create("changed_up");
    private static final BooleanProperty CHANGED_NORTH = BooleanProperty.create("changed_north");
    private static final BooleanProperty CHANGED_SOUTH = BooleanProperty.create("changed_south");
    private static final BooleanProperty CHANGED_WEST = BooleanProperty.create("changed_west");
    private static final BooleanProperty CHANGED_EAST = BooleanProperty.create("changed_east");

    public GrainedCrustBlock(Properties properties) {
        super(properties);
        BlockState state = stateDefinition.any();
        for (Direction side : Direction.values()) {
            state = state.setValue(flagOf(side), false);
        }
        registerDefaultState(state);
    }

    private static BooleanProperty flagOf(Direction side) {
        return switch (side) {
            case DOWN -> CHANGED_DOWN;
            case UP -> CHANGED_UP;
            case NORTH -> CHANGED_NORTH;
            case SOUTH -> CHANGED_SOUTH;
            case WEST -> CHANGED_WEST;
            case EAST -> CHANGED_EAST;
        };
    }

    @Override
    protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder) {
        builder.add(CHANGED_DOWN, CHANGED_UP, CHANGED_NORTH, CHANGED_SOUTH, CHANGED_WEST, CHANGED_EAST);
    }

    /** A neighbour that became solid or a fluid sets its side's flag and the tick that deals with it. The grained crust and the breach crust never count. */
    @Override
    protected BlockState updateShape(
            BlockState state,
            LevelReader level,
            ScheduledTickAccess ticks,
            BlockPos pos,
            Direction direction,
            BlockPos neighborPos,
            BlockState neighborState,
            RandomSource random) {
        if (!GrainedCrust.sheds(neighborState)) {
            return state;
        }
        ticks.scheduleTick(pos, this, 1);
        return state.setValue(flagOf(direction), true);
    }

    @Override
    protected void tick(BlockState state, ServerLevel level, BlockPos pos, RandomSource random) {
        LoadedBlocks blocks = new LoadedBlocks(level);
        BlockState now = state;
        boolean waiting = false;
        List<BlockPos> absorbs = new ArrayList<>();
        List<BlockPos> crumbles = new ArrayList<>();
        for (Direction side : Direction.values()) {
            BooleanProperty flag = flagOf(side);
            if (!state.getValue(flag)) {
                continue;
            }
            BlockPos at = pos.relative(side);
            if (!blocks.canChange(at)) {
                waiting = true;
                continue;
            }
            BlockState neighbour = level.getBlockState(at);
            if (neighbour.getBlock() instanceof LiquidBlock) {
                absorbs.add(at);
            } else if (GrainedCrust.sheds(neighbour)) {
                if (!GrainedCrust.isPulse(level)) {
                    waiting = true;
                    continue;
                }
                crumbles.add(at);
            }
            now = now.setValue(flag, false);
        }
        if (now != state) {
            // The flags are bookkeeping: no client draws them, so nothing is sent. They are cleared before the blocks
            // go: a block that leaves a fluid behind (a waterlogged slab) flags this side again, and the next tick
            // absorbs the fluid.
            level.setBlock(pos, now, Block.UPDATE_INVISIBLE | Block.UPDATE_KNOWN_SHAPE);
        }
        absorbs.forEach(at -> absorb(level, at));
        crumbles.forEach(at -> crumble(level, at));
        if (waiting) {
            level.scheduleTick(pos, this, 1);
        }
    }

    /** PLACEHOLDER sound and particles until the sound and art passes. */
    private static void absorb(ServerLevel level, BlockPos at) {
        // removeBlock would put the fluid back: it sets the block's own fluid in place of it.
        level.setBlock(at, Blocks.AIR.defaultBlockState(), Block.UPDATE_ALL);
        level.playSound(null, at, SoundEvents.SPONGE_ABSORB, SoundSource.BLOCKS, 0.6F, 0.7F);
        level.sendParticles(
                ParticleTypes.SMOKE, at.getX() + 0.5, at.getY() + 0.5, at.getZ() + 0.5, 6, 0.25, 0.25, 0.25, 0.01);
    }

    /** The block breaks as it would in a hand, with its dust and sound, and drops nothing. */
    private static void crumble(ServerLevel level, BlockPos at) {
        level.destroyBlock(at, false);
        level.playSound(null, at, SoundEvents.CREAKING_SWAY, SoundSource.BLOCKS, 0.8F, 0.5F);
    }
}

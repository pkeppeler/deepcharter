#!/usr/bin/env python3
"""Writes gradle/client-test-weights.txt from client GameTest job logs (#1553).

A class's seconds are the gap between its `CLIENT-GAMETEST START` line and the next one in the shard's log; a shard's
last class runs to the log's final `BUILD SUCCESSFUL` line. Each run's times are scaled so its total over the classes
every run ran equals the mean of those totals (runner speed varies about 1.3x), then each class gets the mean over the
runs that ran it, rounded, at least 1 (the least the file accepts). Use at least three runs, and give every shard's log
of a run under one --run.

Usage: tools/py tools/client_weights.py [--out FILE] --run LABEL LOG... [--run LABEL LOG...]...
  LABEL names the run in the file header, for example "46042722092 (7b52fef1)".
  Fetch a shard's log with: gh api repos/pkeppeler/deepcharter/actions/jobs/<job id>/logs > shard1.log
"""

from __future__ import annotations

import argparse
import datetime
from pathlib import Path

START = "CLIENT-GAMETEST START "
END = "BUILD SUCCESSFUL"
# 26 characters cover the date, the time and six fractional digits of a log line's timestamp.
STAMP_LENGTH = 26

HEADER = """\
# Client GameTest weights for -PclientShard=i/n (gradle/gametest.gradle.kts): `<simple class name> <seconds>`.
# Generated by tools/client_weights.py, never by hand. Seconds: the mean over CI runs {runs} of the gap between a class's START line and the next one in each shard's client job log, the last class of a shard running to the job's final `BUILD SUCCESSFUL` line. Each run's times are scaled so its total over the classes every run ran equals the mean total (runner speed varied about 1.3x). Rounded, at least 1, the least the file accepts: a class at 1 starts and ends within a second.
# A name is simple, or fully qualified when two classes share a simple name (the full name wins). A class not listed counts as 10 s, and a name ending in Scenario as 1 s, so a new class needs no entry here and the shards still cover every
# class; an entry for a class that no longer exists is ignored. Stale numbers only unbalance the shards, never
# drop a test. Refresh from green client job logs when the shard wall times drift apart, with at least three runs, so one loaded runner does not skew a class.
"""


def stamp(line: str) -> datetime.datetime:
    return datetime.datetime.fromisoformat(line[:STAMP_LENGTH])


def class_seconds(log: str) -> dict[str, float]:
    """Seconds per class in one shard's job log."""
    lines = log.splitlines()
    starts = [(stamp(line), line.split(START, 1)[1].strip()) for line in lines if START in line]
    ends = [stamp(line) for line in lines if END in line]
    if not starts:
        raise ValueError("no CLIENT-GAMETEST START line in the log")
    if not ends:
        raise ValueError(f"no {END} line in the log, so its last class has no end")
    boundaries = [when for when, _ in starts[1:]] + [ends[-1]]
    return {name: (end - begin).total_seconds() for (begin, name), end in zip(starts, boundaries)}


def weights(runs: list[dict[str, float]]) -> dict[str, int]:
    """Weights from the runs' class seconds, normalised and averaged."""
    common = set.intersection(*(set(run) for run in runs))
    totals = [sum(run[name] for name in common) for run in runs]
    mean_total = sum(totals) / len(totals)
    scaled = [{name: seconds * mean_total / total for name, seconds in run.items()} for run, total in zip(runs, totals)]
    names = set().union(*runs)
    result = {}
    for name in names:
        seen = [run[name] for run in scaled if name in run]
        result[name] = max(1, round(sum(seen) / len(seen)))
    return result


def render(weight_by_class: dict[str, int], labels: list[str]) -> str:
    entries = "".join(f"{name} {seconds}\n" for name, seconds in sorted(weight_by_class.items()))
    return HEADER.format(runs=" and ".join(labels)) + entries


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=Path("gradle/client-test-weights.txt"))
    parser.add_argument("--run", action="append", nargs="+", metavar=("LABEL", "LOG"), required=True)
    args = parser.parse_args()
    labels = []
    runs = []
    for label, *logs in args.run:
        if not logs:
            parser.error(f"--run {label} has no log")
        merged: dict[str, float] = {}
        for log in logs:
            merged.update(class_seconds(Path(log).read_text(errors="replace")))
        labels.append(label)
        runs.append(merged)
    if len(runs) < 3:
        parser.error("average at least three runs, so one loaded runner does not skew a class")
    args.out.write_text(render(weights(runs), labels))


if __name__ == "__main__":
    main()

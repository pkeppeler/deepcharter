from __future__ import annotations

import json
import re
import subprocess
import sys
from dataclasses import dataclass, replace
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from closing_refs import closing_issue_numbers  # noqa: E402

REPO = "pkeppeler/deepcharter"
ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docs" / "ROADMAP.md"
ADR_DIR = ROOT / "docs" / "adr"
HANDOFF_LABEL = "handoff"
# Pipeline order, earliest stage first.
STAGE_LABELS = ("stage:implemented", "stage:reviewed", "stage:simplified", "review-passed")
STAGE_WORDS = {
    "stage:implemented": "Implemented, waiting for review",
    "stage:reviewed": "Reviewed, waiting for simplify",
    "stage:simplified": "Simplified, waiting for final review",
    "review-passed": "Review passed, ready to merge",
}
NO_STAGE_WORD = "No stage yet"
CLOSE_WORDS = {"COMPLETED": "Completed", "NOT_PLANNED": "Not planned"}

@dataclass(frozen=True)
class Link:
    number: int
    url: str


@dataclass(frozen=True)
class Handoff:
    title: str
    url: str


@dataclass(frozen=True)
class Issue:
    number: int
    title: str
    url: str
    closed: bool
    close_reason: str | None  # GitHub state reason (COMPLETED, NOT_PLANNED), only for closed issues
    closed_by: tuple[Link, ...]  # merged PRs only


@dataclass(frozen=True)
class Milestone:
    number: int
    title: str
    description: str
    issues: tuple[Issue, ...]


@dataclass(frozen=True)
class PullRequest:
    number: int
    title: str
    url: str
    draft: bool
    labels: tuple[str, ...]
    closes: tuple[Link, ...]


@dataclass(frozen=True)
class Doc:
    path: str  # relative to docs/
    title: str


@dataclass(frozen=True)
class Roadmap:
    milestones: tuple[Milestone, ...]  # in milestone-number order
    pull_requests: tuple[PullRequest, ...]
    handoff: Handoff | None
    adrs: tuple[Doc, ...]


class RoadmapError(Exception):
    pass


# ---------------------------------------------------------------- rendering


def status_word(closed: int, total: int) -> str:
    if total == 0:
        return "No issues yet"
    if closed == total:
        return "Done"
    if closed == 0:
        return "Not started"
    return "In progress"


def _text(s: str) -> str:
    return " ".join(s.split()).replace("[", "\\[").replace("]", "\\]")


def _stage(labels: tuple[str, ...]) -> str:
    for label in reversed(STAGE_LABELS):
        if label in labels:
            return STAGE_WORDS[label]
    return NO_STAGE_WORD


def _render_issue(issue: Issue) -> str:
    link = f"[#{issue.number} {_text(issue.title)}]({issue.url})"
    if not issue.closed:
        return f"- [ ] Open: {link}"
    word = CLOSE_WORDS.get(issue.close_reason or "", "Closed")
    if issue.closed_by:
        prs = ", ".join(f"[PR #{p.number}]({p.url})" for p in issue.closed_by)
        return f"- [x] {word} by {prs}: {link}"
    return f"- [x] {word} (no PR): {link}"


def render(roadmap: Roadmap, updated: str) -> str:
    out = [
        "# Deep Charter roadmap",
        "",
        "Generated by tools/roadmap.py: do not edit",
        "",
        f"Last updated: {updated} UTC",
        "",
        "## Links",
        "",
    ]
    if roadmap.handoff:
        out.append(f"- Session handoff: [{_text(roadmap.handoff.title)}]({roadmap.handoff.url})")
    else:
        out.append("- Session handoff: none found")
    out.append("- Spec: [SPEC.md](SPEC.md)")
    out.append("- Decisions (ADRs):")
    for adr in roadmap.adrs:
        out.append(f"  - [{_text(adr.title)}]({adr.path})")
    out += ["", "## In flight", ""]
    if roadmap.pull_requests:
        for pr in roadmap.pull_requests:
            draft = " (draft)" if pr.draft else ""
            out.append(f"- [PR #{pr.number} {_text(pr.title)}]({pr.url}){draft}")
            out.append(f"  - Stage: {_stage(pr.labels)}")
            if pr.closes:
                issues = ", ".join(f"[#{i.number}]({i.url})" for i in pr.closes)
                out.append(f"  - Closes: {issues}")
    else:
        out.append("Nothing in flight.")
    out += ["", "## Milestones"]
    for m in roadmap.milestones:
        total = len(m.issues)
        closed = sum(1 for i in m.issues if i.closed)
        out += [
            "",
            f"### {_text(m.title)}",
            "",
            f"Status: {status_word(closed, total)} ({closed} of {total} closed)",
        ]
        if m.description.strip():
            out += ["", " ".join(m.description.split())]
        out.append("")
        if m.issues:
            out += [_render_issue(i) for i in m.issues]
        else:
            out.append("No issues yet.")
    return "\n".join(out) + "\n"


# ----------------------------------------------------------------- fetching


def gh_rest(path: str) -> list[dict]:
    """Every item of a REST list endpoint, all pages."""
    cmd = ["gh", "api", "--paginate", "--slurp", f"repos/{REPO}/{path}"]
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, check=False)
    except FileNotFoundError:
        raise RoadmapError("gh is not installed or not on PATH") from None
    if proc.returncode != 0:
        raise RoadmapError(f"gh failed (exit {proc.returncode}): {proc.stderr.strip()}")
    try:
        pages = json.loads(proc.stdout)
    except json.JSONDecodeError as e:
        raise RoadmapError(f"gh returned invalid JSON: {e}") from None
    return [item for page in pages for item in page]


def _issue_url(number: int) -> str:
    return f"https://github.com/{REPO}/issues/{number}"


def _pr_url(number: int) -> str:
    return f"https://github.com/{REPO}/pull/{number}"


def build_roadmap(
    milestones: list[dict],
    issues_by_milestone: dict[int, list[dict]],
    pulls: list[dict],
    handoffs: list[dict],
    adrs: tuple[Doc, ...],
) -> Roadmap:
    """The roadmap from REST records. `pulls` is every PR (all states): REST has no closing-PR link, so an issue's
    closing PRs are the merged PRs whose body closes it (tools/closing_refs.py), in PR-number order."""
    pulls = sorted(pulls, key=lambda p: p["number"])
    closed_by: dict[int, list[Link]] = {}
    for p in pulls:
        if p["merged_at"] is None:
            continue
        for number in closing_issue_numbers(p["body"] or "", REPO):
            closed_by.setdefault(number, []).append(Link(p["number"], p["html_url"]))
    built = []
    for m in milestones:
        issues = []
        for i in issues_by_milestone[m["number"]]:
            if "pull_request" in i:
                continue
            closed = i["state"] == "closed"
            reason = (i.get("state_reason") or "").upper() if closed else None
            issues.append(
                Issue(
                    number=i["number"],
                    title=i["title"],
                    url=i["html_url"],
                    closed=closed,
                    close_reason=reason or None,
                    closed_by=tuple(closed_by.get(i["number"], ())),
                )
            )
        built.append(Milestone(m["number"], m["title"], m["description"] or "", tuple(issues)))
    prs = [
        PullRequest(
            number=p["number"],
            title=p["title"],
            url=p["html_url"],
            draft=p["draft"],
            labels=tuple(sorted(label["name"] for label in p["labels"])),
            closes=tuple(Link(n, _issue_url(n)) for n in closing_issue_numbers(p["body"] or "", REPO)),
        )
        for p in pulls
        if p["state"] == "open"
    ]
    handoffs = [i for i in handoffs if "pull_request" not in i]
    if len(handoffs) > 1:
        raise RoadmapError(f"expected one open '{HANDOFF_LABEL}' issue, found {len(handoffs)}")
    handoff = Handoff(handoffs[0]["title"], handoffs[0]["html_url"]) if handoffs else None
    return Roadmap(tuple(sorted(built, key=lambda m: m.number)), tuple(prs), handoff, adrs)


def read_adrs() -> tuple[Doc, ...]:
    docs = []
    for path in sorted(ADR_DIR.glob("*.md")):
        match = re.search(r"^# (.+)$", path.read_text(encoding="utf-8"), re.MULTILINE)
        if not match:
            raise RoadmapError(f"{path} has no '# ' heading")
        docs.append(Doc(f"adr/{path.name}", match.group(1).strip()))
    return tuple(docs)


def fetch() -> Roadmap:
    milestones = gh_rest("milestones?state=all&per_page=100")
    issues = {
        m["number"]: gh_rest(f"issues?milestone={m['number']}&state=all&sort=created&direction=asc&per_page=100")
        for m in milestones
    }
    pulls = gh_rest("pulls?state=all&per_page=100")
    handoffs = gh_rest(f"issues?labels={HANDOFF_LABEL}&state=open&per_page=100")
    return build_roadmap(milestones, issues, pulls, handoffs, read_adrs())


USAGE = "usage: tools/py tools/roadmap.py [--landing <pr>:<issue>]... [--hide <pr>]..."


def apply_landing(roadmap: Roadmap, landing: tuple[tuple[int, int], ...], hide: tuple[int, ...]) -> Roadmap:
    """The roadmap as it reads once the (PR, issue) pairs in `landing` have merged: each issue is closed as completed
    by its PR, and neither that PR nor a `hide` PR (the batch's own) is in flight. The batch tool renders this before
    its landing push, when GitHub still shows the issues open (#1567)."""
    pr_of = {issue: pr for pr, issue in landing}
    gone = {pr for pr, _ in landing} | set(hide)
    milestones = []
    for m in roadmap.milestones:
        issues = []
        for i in m.issues:
            pr = pr_of.get(i.number)
            if pr is None:
                issues.append(i)
                continue
            linked = any(link.number == pr for link in i.closed_by)
            by = i.closed_by if linked else (*i.closed_by, Link(pr, _pr_url(pr)))
            issues.append(replace(i, closed=True, close_reason=i.close_reason or "COMPLETED", closed_by=by))
        milestones.append(replace(m, issues=tuple(issues)))
    prs = tuple(p for p in roadmap.pull_requests if p.number not in gone)
    return replace(roadmap, milestones=tuple(milestones), pull_requests=prs)


def parse_args(argv: list[str]) -> tuple[tuple[tuple[int, int], ...], tuple[int, ...]]:
    landing: list[tuple[int, int]] = []
    hide: list[int] = []
    args = iter(argv)
    for flag in args:
        value = next(args, "")
        if flag == "--landing" and re.fullmatch(r"\d+:\d+", value):
            pr, issue = value.split(":")
            landing.append((int(pr), int(issue)))
        elif flag == "--hide" and value.isdigit():
            hide.append(int(value))
        else:
            raise ValueError(f"{flag} {value}".strip())
    return tuple(landing), tuple(hide)


def main() -> int:
    try:
        landing, hide = parse_args(sys.argv[1:])
    except ValueError as e:
        print(f"roadmap.py: cannot read '{e}'\n{USAGE}", file=sys.stderr)
        return 2
    try:
        roadmap = apply_landing(fetch(), landing, hide)
    except RoadmapError as e:
        print(f"roadmap.py: {e}", file=sys.stderr)
        return 1
    updated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M")
    OUTPUT.write_text(render(roadmap, updated), encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

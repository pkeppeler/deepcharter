from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from dataclasses import dataclass
from datetime import datetime, timezone

HANDOFF_LABEL = "handoff"
ROADMAP_LABEL = "roadmap"
SLUG_PATTERN = re.compile(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+")
USAGE = "usage: python3 -I tools/roadmap.py [--publish]"
# Pipeline order, earliest stage first.
STAGE_LABELS = ("stage:implemented", "stage:reviewed", "stage:simplified", "review-passed")
STAGE_WORDS = {
    "stage:implemented": "Implemented, waiting for review",
    "stage:reviewed": "Reviewed, waiting for simplify",
    "stage:simplified": "Simplified, waiting for final review",
    "review-passed": "Review passed, ready to merge",
}
NO_STAGE_WORD = "No stage yet"
CLOSE_WORDS = {"COMPLETED": "Completed", "NOT_PLANNED": "Not planned"}
PAGE = 100

QUERY = """
query($owner: String!, $name: String!) {
  repository(owner: $owner, name: $name) {
    milestones(first: %(page)d, orderBy: {field: NUMBER, direction: ASC}) {
      pageInfo { hasNextPage }
      nodes {
        number title description
        issues(first: %(page)d, orderBy: {field: CREATED_AT, direction: ASC}) {
          pageInfo { hasNextPage }
          nodes {
            number title state stateReason url
            closedByPullRequestsReferences(first: 10, includeClosedPrs: true) {
              pageInfo { hasNextPage }
              nodes { number url merged }
            }
          }
        }
      }
    }
    pullRequests(states: OPEN, first: %(page)d, orderBy: {field: CREATED_AT, direction: ASC}) {
      pageInfo { hasNextPage }
      nodes {
        number title url isDraft
        labels(first: 20) { pageInfo { hasNextPage } nodes { name } }
        closingIssuesReferences(first: 10) { pageInfo { hasNextPage } nodes { number url } }
      }
    }
    handoff: issues(labels: ["%(handoff)s"], states: OPEN, first: 5) {
      pageInfo { hasNextPage }
      nodes { number title url }
    }
  }
}
""" % {"page": PAGE, "handoff": HANDOFF_LABEL}


@dataclass(frozen=True)
class Link:
    number: int
    url: str


@dataclass(frozen=True)
class Handoff:
    title: str
    url: str


@dataclass(frozen=True)
class Issue:
    number: int
    title: str
    url: str
    closed: bool
    close_reason: str | None  # GitHub stateReason, only for closed issues
    closed_by: tuple[Link, ...]  # merged PRs only


@dataclass(frozen=True)
class Milestone:
    number: int
    title: str
    description: str
    issues: tuple[Issue, ...]


@dataclass(frozen=True)
class PullRequest:
    number: int
    title: str
    url: str
    draft: bool
    labels: tuple[str, ...]
    closes: tuple[Link, ...]


@dataclass(frozen=True)
class Roadmap:
    milestones: tuple[Milestone, ...]  # in milestone-number order
    pull_requests: tuple[PullRequest, ...]
    handoff: Handoff | None


class RoadmapError(Exception):
    pass


# ---------------------------------------------------------------- rendering


def status_word(closed: int, total: int) -> str:
    if total == 0:
        return "No issues yet"
    if closed == total:
        return "Done"
    if closed == 0:
        return "Not started"
    return "In progress"


def _text(s: str) -> str:
    return " ".join(s.split()).replace("[", "\\[").replace("]", "\\]")


def _stage(labels: tuple[str, ...]) -> str:
    for label in reversed(STAGE_LABELS):
        if label in labels:
            return STAGE_WORDS[label]
    return NO_STAGE_WORD


def _render_issue(issue: Issue) -> str:
    link = f"[#{issue.number} {_text(issue.title)}]({issue.url})"
    if not issue.closed:
        return f"- [ ] Open: {link}"
    word = CLOSE_WORDS.get(issue.close_reason or "", "Closed")
    if issue.closed_by:
        prs = ", ".join(f"[PR #{p.number}]({p.url})" for p in issue.closed_by)
        return f"- [x] {word} by {prs}: {link}"
    return f"- [x] {word} (no PR): {link}"


def render(roadmap: Roadmap, updated: str) -> str:
    out = [
        "# Roadmap",
        "",
        "Generated by tools/roadmap.py: do not edit",
        "",
        f"Last updated: {updated} UTC",
        "",
        "## Links",
        "",
    ]
    if roadmap.handoff:
        out.append(f"- Session handoff: [{_text(roadmap.handoff.title)}]({roadmap.handoff.url})")
    else:
        out.append("- Session handoff: none found")
    out += ["", "## In flight", ""]
    if roadmap.pull_requests:
        for pr in roadmap.pull_requests:
            draft = " (draft)" if pr.draft else ""
            out.append(f"- [PR #{pr.number} {_text(pr.title)}]({pr.url}){draft}")
            out.append(f"  - Stage: {_stage(pr.labels)}")
            if pr.closes:
                issues = ", ".join(f"[#{i.number}]({i.url})" for i in pr.closes)
                out.append(f"  - Closes: {issues}")
    else:
        out.append("Nothing in flight.")
    out += ["", "## Milestones"]
    for m in roadmap.milestones:
        total = len(m.issues)
        closed = sum(1 for i in m.issues if i.closed)
        out += [
            "",
            f"### {_text(m.title)}",
            "",
            f"Status: {status_word(closed, total)} ({closed} of {total} closed)",
        ]
        if m.description.strip():
            out += ["", " ".join(m.description.split())]
        out.append("")
        if m.issues:
            out += [_render_issue(i) for i in m.issues]
        else:
            out.append("No issues yet.")
    return "\n".join(out) + "\n"


# ----------------------------------------------------------------- fetching


def gh(args: list[str], stdin: str | None = None) -> str:
    cmd = ["gh", *args]
    try:
        proc = subprocess.run(cmd, input=stdin, capture_output=True, text=True, check=False)
    except FileNotFoundError:
        raise RoadmapError("gh is not installed or not on PATH") from None
    if proc.returncode != 0:
        raise RoadmapError(f"gh failed (exit {proc.returncode}): {proc.stderr.strip()}")
    return proc.stdout


def resolve_repo() -> str:
    slug = os.environ.get("REPO") or gh(["repo", "view", "--json", "nameWithOwner", "--jq", ".nameWithOwner"]).strip()
    if not SLUG_PATTERN.fullmatch(slug):
        raise RoadmapError(f"{slug!r} is not an owner/name slug")
    return slug


def gh_graphql(repo: str) -> dict:
    owner, name = repo.split("/")
    out = gh(["api", "graphql", "-f", f"query={QUERY}", "-f", f"owner={owner}", "-f", f"name={name}"])
    try:
        data = json.loads(out)
    except json.JSONDecodeError as e:
        raise RoadmapError(f"gh returned invalid JSON: {e}") from None
    if data.get("errors"):
        raise RoadmapError(f"GraphQL errors: {data['errors']}")
    return data["data"]


def _require_complete(connection: dict, what: str) -> None:
    if connection["pageInfo"]["hasNextPage"]:
        raise RoadmapError(f"too many {what}: add pagination to tools/roadmap.py")


def parse_github(repository: dict) -> Roadmap:
    _require_complete(repository["milestones"], "milestones")
    _require_complete(repository["pullRequests"], "open PRs")
    _require_complete(repository["handoff"], f"open '{HANDOFF_LABEL}' issues")
    milestones = []
    for m in repository["milestones"]["nodes"]:
        _require_complete(m["issues"], f"issues in milestone {m['title']}")
        issues = []
        for i in m["issues"]["nodes"]:
            closers = i["closedByPullRequestsReferences"]
            _require_complete(closers, f"closing PRs for issue #{i['number']}")
            issues.append(
                Issue(
                    number=i["number"],
                    title=i["title"],
                    url=i["url"],
                    closed=i["state"] == "CLOSED",
                    close_reason=i["stateReason"],
                    closed_by=tuple(Link(p["number"], p["url"]) for p in closers["nodes"] if p["merged"]),
                )
            )
        milestones.append(Milestone(m["number"], m["title"], m["description"] or "", tuple(issues)))
    prs = []
    for p in repository["pullRequests"]["nodes"]:
        _require_complete(p["labels"], f"labels on PR #{p['number']}")
        _require_complete(p["closingIssuesReferences"], f"closing issues on PR #{p['number']}")
        prs.append(
            PullRequest(
                number=p["number"],
                title=p["title"],
                url=p["url"],
                draft=p["isDraft"],
                labels=tuple(sorted(label["name"] for label in p["labels"]["nodes"])),
                closes=tuple(Link(i["number"], i["url"]) for i in p["closingIssuesReferences"]["nodes"]),
            )
        )
    handoffs = repository["handoff"]["nodes"]
    if len(handoffs) > 1:
        raise RoadmapError(f"expected one open '{HANDOFF_LABEL}' issue, found {len(handoffs)}")
    handoff = Handoff(handoffs[0]["title"], handoffs[0]["url"]) if handoffs else None
    return Roadmap(tuple(sorted(milestones, key=lambda m: m.number)), tuple(prs), handoff)


def roadmap_issue_number(repo: str) -> int:
    out = gh(["issue", "list", "--repo", repo, "--label", ROADMAP_LABEL, "--state", "open", "--json", "number", "--limit", "100"])
    try:
        issues = json.loads(out)
    except json.JSONDecodeError as e:
        raise RoadmapError(f"gh returned invalid JSON: {e}") from None
    if len(issues) != 1:
        raise RoadmapError(f"expected one open '{ROADMAP_LABEL}' issue, found {len(issues)}")
    return issues[0]["number"]


def publish(repo: str, body: str) -> None:
    number = roadmap_issue_number(repo)
    gh(["issue", "edit", str(number), "--repo", repo, "--body-file", "-"], stdin=body)


def main() -> int:
    args = sys.argv[1:]
    if args not in ([], ["--publish"]):
        print(USAGE, file=sys.stderr)
        return 2
    try:
        repo = resolve_repo()
        roadmap = parse_github(gh_graphql(repo)["repository"])
        body = render(roadmap, datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M"))
        if args:
            publish(repo, body)
        else:
            print(body, end="")
    except RoadmapError as e:
        print(f"roadmap.py: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env bash
# Usage: tools/merge-batch.sh <pr-number>...
#
# Merges several review-passed PRs with one CI run, as one squashed commit per PR landed by a fast-forward push.
# Steps, retries and the exit status: .claude/skills/deepcharter-conventions/merging.md ("Batches") and ADR 0106.
# The exit trap closes an open batch PR and deletes its branch unless it landed. Shares the merge lock with
# merge-queue.sh (exit 3 when one is running).
#
# Test seams: MERGE_PR (the gate script), MERGE_QUEUE_LOCK, MERGE_BATCH_{CI_POLL,CI_MAX,STALE_SLEEP,PENDING_RETRIES,
# STALE_RETRIES,CLIENT_RETRIES}, MERGE_BATCH_STAMP (the UTC stamp), MERGE_BATCH_TRAILERS (commit trailers, one per
# line; default a Co-Authored-By line).
set -euo pipefail

repo=pkeppeler/deepcharter
root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
merge_pr=${MERGE_PR:-$root/tools/merge-pr.sh}
lock=${MERGE_QUEUE_LOCK:-$HOME/.cache/deepcharter/merge-queue.lock}
ci_poll=${MERGE_BATCH_CI_POLL:-20}
# Must stay above the longest CI job limit (the build job, 45 minutes) plus the changes job lead time.
ci_max=${MERGE_BATCH_CI_MAX:-4200}
stale_sleep=${MERGE_BATCH_STALE_SLEEP:-90}
pending_max=${MERGE_BATCH_PENDING_RETRIES:-10}
stale_max=${MERGE_BATCH_STALE_RETRIES:-3}
client_max=${MERGE_BATCH_CLIENT_RETRIES:-1}
trailers=${MERGE_BATCH_TRAILERS:-Co-Authored-By: Claude <noreply@anthropic.com>}
footer=$'---\n_Generated by [Claude Code](https://claude.ai/code)_'

if [[ $# -lt 1 ]]; then
  echo "usage: tools/merge-batch.sh <pr-number>..." >&2
  exit 2
fi
for arg in "$@"; do
  [[ $arg =~ ^[0-9]+$ ]] || { echo "usage: tools/merge-batch.sh <pr-number>... (got '$arg')" >&2; exit 2; }
done

say() { echo "batch: $*"; }

cd "$root"
mkdir -p "$(dirname "$lock")"
# shellcheck source=lib/merge-lock.sh
source "$root/tools/lib/merge-lock.sh"
acquire_lock
tmp=$(mktemp -d)
roadmap_tmp=
build_wt=
open_bpr=
open_branch=
release() {
  if [[ -n $open_bpr ]]; then retire_batch "$open_bpr" "$open_branch" "Closed: the batch tool stopped before this batch merged."; fi
  if [[ -n $build_wt ]]; then git worktree remove --force "$build_wt" >/dev/null 2>&1 || true; fi
  roadmap_cleanup
  rm -rf "$tmp"
  git worktree prune >/dev/null 2>&1 || true
  if [[ $(readlink "$lock" 2>/dev/null || true) == "$$" ]]; then rm -f "$lock"; fi
}
trap release EXIT
trap 'exit 130' INT TERM

# shellcheck source=lib/gh-rest.sh
source "$root/tools/lib/gh-rest.sh"
# shellcheck source=lib/ci-wait.sh
source "$root/tools/lib/ci-wait.sh"
# shellcheck source=lib/merge-cleanup.sh
source "$root/tools/lib/merge-cleanup.sh"
# shellcheck source=lib/roadmap.sh
source "$root/tools/lib/roadmap.sh"
# shellcheck source=lib/stacked.sh
source "$root/tools/lib/stacked.sh"
# shellcheck source=lib/adr.sh
source "$root/tools/lib/adr.sh"

merged=()
dropped=()
refused=()
stopped=
not_attempted=()
build_seq=0
# Chains: chain_prev[n] is the nearest listed PR (preflight-refused ones too) whose head is an ancestor of n's head
# (n's branch merged it); chain_head[n] is the head sha read when the chains were found.
declare -A chain_prev=()
declare -A chain_head=()

# comment <n> <text>: a comment on an issue or PR.
comment() { gh api -X POST "repos/$repo/issues/$1/comments" -f body="$2" >/dev/null; }

# close_pr <n>: close a PR; the one place a tool closes one (never to kick CI: tools/tests/no-pr-reopen.test.sh).
close_pr() {
  gh api -X PATCH "repos/$repo/pulls/$1" -f state=closed >/dev/null # close-ok: a batch PR superseded, or an original PR merged in its batch
}

# delete_remote_branch <branch>: a branch already gone is fine.
delete_remote_branch() {
  gh api -X DELETE "repos/$repo/git/refs/heads/$1" >/dev/null 2>&1 || true
}

# drop <pr> <reason>
drop() {
  dropped+=("#$1 ($2)")
  say "dropped PR #$1: $2"
}

# drop_reset <pr> <reason>: undo the PR's staged squash in the build worktree, then drop it.
drop_reset() {
  git -C "$build_wt" reset --hard -q HEAD
  drop "$@"
}

# adr_duplicates <worktree>: the ADR numbers that two files in the tree hold, one per line.
adr_duplicates() {
  local files
  files=$(git -C "$1" ls-files docs/adr/ | grep -E "$adr_re" || true)
  sed -E 's#^docs/adr/([0-9]{4})-.*#\1#' <<<"$files" | sort | uniq -d
}

# on_main <pr>: origin/main holds a commit whose subject ends (#<pr>), or the PR is merged.
on_main() {
  [[ -n $(git log -1 --format=%h -E --grep="\\(#$1\\)$" origin/main 2>/dev/null) ]] && return 0
  [[ $(pr_state_of "$1" 2>/dev/null || true) == MERGED ]]
}

# pred_landed <pr>: the PR is squashed onto the batch being built, merged by an earlier group, or on main.
pred_landed() {
  local x
  for x in ${included[@]+"${included[@]}"}; do [[ $x == "$1" ]] && return 0; done
  for x in ${merged[@]+"${merged[@]}"}; do [[ $x == "#$1" || $x == "#$1 "* ]] && return 0; done
  on_main "$1"
}

# find_chains <pr>...: fills chain_prev and chain_head. A PR is chained to the listed PR whose head is its nearest
# proper ancestor: the one no other ancestor found for it descends from. A head it cannot fetch stays unchained
# (build_batch drops it).
find_chains() {
  local n p q anc best
  for n in "$@"; do
    if git fetch origin "refs/pull/$n/head" >/dev/null 2>&1; then chain_head[$n]=$(git rev-parse FETCH_HEAD); fi
  done
  for n in "$@"; do
    [[ -n ${chain_head[$n]:-} ]] || continue
    anc=()
    for p in "$@"; do
      [[ $p != "$n" && -n ${chain_head[$p]:-} && ${chain_head[$p]} != "${chain_head[$n]}" ]] || continue
      if git merge-base --is-ancestor "${chain_head[$p]}" "${chain_head[$n]}" 2>/dev/null; then anc+=("$p"); fi
    done
    best=
    for p in ${anc[@]+"${anc[@]}"}; do
      for q in "${anc[@]}"; do
        [[ $q != "$p" && ${chain_head[$q]} != "${chain_head[$p]}" ]] || continue
        if git merge-base --is-ancestor "${chain_head[$p]}" "${chain_head[$q]}" 2>/dev/null; then continue 2; fi
      done
      best=$p
    done
    if [[ -n $best ]]; then
      chain_prev[$n]=$best
      say "PR #$n is chained to PR #$best"
    fi
  done
}

# order_chains <pr>...: sets the array $ordered, the PRs with every predecessor before its successors, otherwise in the
# given order.
ordered=()
order_chains() {
  local n
  ordered=()
  for n in "$@"; do emit_chained "$n" "$@"; done
}
emit_chained() {
  local n=$1 x prev
  shift
  for x in ${ordered[@]+"${ordered[@]}"}; do [[ $x == "$n" ]] && return 0; done
  prev=${chain_prev[$n]:-}
  if [[ -n $prev ]]; then
    for x in "$@"; do
      if [[ $x == "$prev" ]]; then emit_chained "$prev" "$@"; break; fi
    done
  fi
  ordered+=("$n")
}

# squash_onto_batch <pr> <head>: stages the PR's squash in the build worktree. An unchained PR is a squash merge of
# its head. A chained one is a three-way merge of the batch and its head with its predecessor's head as the merge
# base, so only its own increment lands. Returns 1 on a conflict, 2 when merge-tree fails otherwise.
squash_onto_batch() {
  local n=$1 head=$2 prev tree mt_rc
  prev=${chain_prev[$n]:-}
  if [[ -z $prev ]]; then
    git -C "$build_wt" merge --squash --no-commit "$head" >/dev/null 2>&1
    return
  fi
  mt_rc=0
  tree=$(git -C "$build_wt" merge-tree --write-tree --merge-base="${chain_head[$prev]}" HEAD "$head" 2>/dev/null) || mt_rc=$?
  ((mt_rc == 0)) || return $((mt_rc == 1 ? 1 : 2))
  git -C "$build_wt" read-tree --reset -u "$tree"
}

# build_batch <pr>...: sets $b_branch, $b_sha and the array $included (the PRs squashed onto it); drops the rest.
# The worktree is removed before it returns. Never resolves a conflict.
build_batch() {
  local n head fetched title branch issue msg dup stamp landed sq_rc
  build_seq=$((build_seq + 1))
  stamp=${MERGE_BATCH_STAMP:-$(date -u +%Y%m%dT%H%M%SZ)}
  b_branch=batch/$stamp
  if ((build_seq > 1)); then b_branch+="-$build_seq"; fi
  included=()
  git fetch origin main >/dev/null 2>&1 || { stopped="could not fetch origin/main"; return 1; }
  build_wt=$tmp/wt-$build_seq
  b_base=$(git rev-parse origin/main)
  git worktree add -b "$b_branch" "$build_wt" origin/main >/dev/null 2>&1 \
    || { build_wt=; stopped="could not create the batch worktree for $b_branch"; return 1; }
  for n in "$@"; do
    head=$(pr_get "$n" .head.sha 2>/dev/null) || { drop "$n" "could not read its head sha"; continue; }
    if ! git fetch origin "refs/pull/$n/head" >/dev/null 2>&1; then
      drop "$n" "could not fetch refs/pull/$n/head"
      continue
    fi
    fetched=$(git rev-parse FETCH_HEAD)
    if [[ $fetched != "$head" ]]; then
      drop "$n" "head moved from ${head:0:9} to ${fetched:0:9} while building; its review pass no longer covers it"
      continue
    fi
    if [[ -n ${chain_prev[$n]:-} ]]; then
      if ! pred_landed "${chain_prev[$n]}"; then
        drop "$n" "chained to #${chain_prev[$n]}, which did not land"
        continue
      fi
      if [[ $head != "${chain_head[$n]}" ]]; then
        drop "$n" "head moved from ${chain_head[$n]:0:9} to ${head:0:9} after its chain was found"
        continue
      fi
    fi
    sq_rc=0
    squash_onto_batch "$n" "$head" || sq_rc=$?
    if ((sq_rc == 2)); then
      drop_reset "$n" "git merge-tree failed on its chain (not a conflict)"
      continue
    elif ((sq_rc != 0)); then
      drop_reset "$n" "conflicts with main or an earlier PR in the batch"
      continue
    fi
    if git -C "$build_wt" diff --cached --quiet; then
      landed=$(git log -1 --format=%h --fixed-strings --grep="(#$n)" origin/main)
      if [[ -n $landed ]]; then
        say "PR #$n is already on main as $landed: closing it as merged"
        close_original "$n" "Merged in batch (already on main as $landed, from an earlier batch run)"
        merged+=("#$n (already on main)")
      else
        drop "$n" "adds nothing to the batch (already on main?)"
      fi
      continue
    fi
    dup=$(adr_duplicates "$build_wt")
    if [[ -n $dup ]]; then
      drop_reset "$n" "its ADR number ($(tr '\n' ' ' <<<"$dup" | sed 's/ $//')) is already taken on the batch"
      continue
    fi
    title=$(pr_get "$n" .title) || { drop_reset "$n" "could not read its title"; continue; }
    branch=$(pr_get "$n" .head.ref) || branch=
    [[ $branch =~ ^([0-9]+)- ]] || { drop_reset "$n" "branch '$branch' is not <issue>-<slug>"; continue; }
    issue=${BASH_REMATCH[1]}
    msg="$title (#$n)"$'\n\n'"Closes #$issue"$'\n\n'"$trailers"
    git -C "$build_wt" commit -q --no-verify -m "$msg" || { drop_reset "$n" "could not commit its squash"; continue; }
    included+=("$n")
  done
  b_sha=$(git -C "$build_wt" rev-parse HEAD)
  git worktree remove --force "$build_wt" >/dev/null 2>&1 || true
  build_wt=
}

# discard_local_branch <branch>
discard_local_branch() { git branch -D "$1" >/dev/null 2>&1 || true; }

# open_batch_pr <pr>...: pushes $b_branch, opens the PR and labels it. Sets $bpr. Returns 1 with $stopped set.
open_batch_pr() {
  local list="" body="" n title branch issue
  for n in "$@"; do
    title=$(pr_get "$n" .title) || title=
    branch=$(pr_get "$n" .head.ref) || branch=
    issue=
    if [[ $branch =~ ^([0-9]+)- ]]; then issue=${BASH_REMATCH[1]}; fi
    list+="#$n "
    body+="- #$n $title"$'\n'"  Closes #$issue"$'\n'
  done
  body="Batch of $# review-passed PRs, squashed one commit each onto main and landed by a fast-forward push after one CI run (ADR 0106)."$'\n\n'"What it does:"$'\n\n'"$body"$'\n'
  body+="No demo: tooling only; each batched PR carries its own evidence and was reviewed on its own."$'\n'
  body+="No map change: each batched PR carries its own map change."$'\n\n'"$footer"
  git push origin "$b_branch" >/dev/null 2>&1 || { stopped="could not push $b_branch"; return 1; }
  bpr=$(gh api -X POST "repos/$repo/pulls" -f title="Batch: ${list% }" -f head="$b_branch" -f base=main -f body="$body" --jq .number) \
    || { stopped="could not open the batch PR for $b_branch"; return 1; }
  [[ $bpr =~ ^[0-9]+$ ]] || { stopped="the batch PR for $b_branch has no readable number"; return 1; }
  open_bpr=$bpr
  open_branch=$b_branch
  gh api -X POST "repos/$repo/issues/$bpr/labels" -f 'labels[]=gameplay' -f 'labels[]=no-demo' >/dev/null \
    || { stopped="could not label batch PR #$bpr (it must carry gameplay and no-demo)"; return 1; }
  say "opened batch PR #$bpr from $b_branch"
}

# retire_batch <bpr> <branch> <why>: close a batch PR that will not merge, delete its branches.
retire_batch() {
  open_bpr=
  comment "$1" "$3"$'\n\n'"$footer" || true
  close_pr "$1" || true
  delete_remote_branch "$2"
  discard_local_branch "$2"
}

# close_original <pr> <comment>: comment on a PR that is on main, close it, retarget the PRs stacked on its branch to
# main, delete its branch and clean up its worktree.
close_original() {
  local n=$1 branch sha
  branch=$(pr_get "$n" .head.ref 2>/dev/null || true)
  sha=$(pr_get "$n" .head.sha 2>/dev/null || true)
  comment "$n" "$2"$'\n\n'"$footer" || say "could not comment on PR #$n"
  close_pr "$n" || say "could not close PR #$n"
  [[ -n $branch ]] || return 0
  if retarget_stacked "$branch" main; then
    delete_remote_branch "$branch"
    cleanup_pr "$branch" "$sha"
  else
    say "left: branch $branch ($retarget_err)"
  fi
}

# finish_originals <batch pr> <pr>...: after the batch merged, close each original and delete its branch.
finish_originals() {
  local bpr_n=$1 n
  shift
  for n in "$@"; do
    close_original "$n" "Merged in batch #$bpr_n"
    merged+=("#$n")
  done
}

# merge_single <pr>: a group of one goes through the gate alone, with the queue's stale-base handling.
merge_single() {
  local n=$1 branch sha out rc state reason stale_n=0
  if [[ -n ${chain_prev[$n]:-} ]]; then
    included=()
    git fetch origin main >/dev/null 2>&1 || true
    if ! pred_landed "${chain_prev[$n]}"; then
      drop "$n" "chained to #${chain_prev[$n]}, which did not land"
      return 0
    fi
  fi
  say "PR #$n alone: tools/merge-pr.sh"
  branch=$(pr_get "$n" .head.ref 2>/dev/null || true)
  while true; do
    sha=$(pr_get "$n" .head.sha 2>/dev/null || true)
    if [[ -n $branch && -n $sha ]] && ! wait_ci "$branch" "$sha"; then
      refused+=("#$n (CI on ${sha:0:9} still unfinished after ${ci_max}s)")
      return 0
    fi
    rc=0
    out=$("$merge_pr" "$n" 2>&1) || rc=$?
    [[ -z $out ]] || echo "$out"
    state=$(pr_state_of "$n" 2>/dev/null || echo unknown)
    if [[ $state == MERGED ]]; then
      merged+=("#$n")
      [[ -z $branch ]] || cleanup_pr "$branch" "$sha"
      return 0
    fi
    reason=$(grep -m1 -E '^(REFUSED|ERROR):' <<<"$out" || true)
    [[ -n $reason ]] || reason="the gate exited $rc: $(tail -n 1 <<<"$out")"
    if [[ $out == *"[stale-base]"* ]]; then
      if ((stale_n >= stale_max)); then
        refused+=("#$n ($reason; still stale after $stale_max reruns)")
        return 0
      fi
      stale_n=$((stale_n + 1))
      say "PR #$n has a stale base; re-running CI ($stale_n of $stale_max)"
      if ! rerun_ci "$n" "$sha"; then
        refused+=("#$n ($rerun_err)")
        return 0
      fi
      sleep "$stale_sleep"
    else
      refused+=("#$n ($reason)")
      return 0
    fi
  done
}

# process_group <pr>...: merge them as one batch, or split on red. Sets $stopped when the tool must stop.
process_group() {
  local prs=("$@") stale_n=0 client_n=0 pending_n=0 half out rc sha verdict reason push_out
  if [[ -n $stopped ]]; then
    not_attempted+=("${prs[@]/#/#}")
    return 0
  fi
  if ((${#prs[@]} == 1)); then
    merge_single "${prs[0]}"
    return 0
  fi
  while true; do
    build_batch "${prs[@]}" || return 0
    prs=(${included[@]+"${included[@]}"})
    if ((${#prs[@]} == 0)); then
      discard_local_branch "$b_branch"
      return 0
    fi
    if ((${#prs[@]} == 1)); then
      discard_local_branch "$b_branch"
      merge_single "${prs[0]}"
      return 0
    fi
    say "batch $b_branch holds ${prs[*]/#/#}"
    open_batch_pr "${prs[@]}" || return 0
    sha=$b_sha
    verdict=
    while [[ -z $verdict ]]; do
      reason=
      if ! wait_ci "$b_branch" "$sha"; then
        stopped="batch PR #$bpr: CI on ${sha:0:9} still unfinished after ${ci_max}s"
        return 0
      fi
      rc=0
      out=$("$merge_pr" --ci "$bpr" 2>&1) || rc=$?
      [[ -z $out ]] || echo "$out"
      reason=$(grep -m1 -E '^(REFUSED|ERROR):' <<<"$out" || true)
      if ((rc == 0)); then
        verdict=green
      elif [[ $out == *"[stale-base]"* ]]; then
        verdict=stale
      elif [[ $out == *"[client-only]"* ]]; then
        if ((client_n >= client_max)); then
          verdict=red
        else
          client_n=$((client_n + 1))
          say "batch PR #$bpr failed only client checks; re-running the whole Client tests run ($client_n of $client_max)"
          if ! rerun_ci "$bpr" "$sha" "Client tests|client-gametest|0"; then
            stopped=$rerun_err
            return 0
          fi
          sleep "$stale_sleep"
        fi
      elif [[ $out == *"has no checks reported"* || $out == *"lacks required check"* || $out == *"only skipped"* \
        || $out =~ newest\ non-skipped\ run:\ (queued|in_progress|waiting|pending|requested) ]]; then
        if ((pending_n >= pending_max)); then
          stopped="batch PR #$bpr: CI did not finish or report its checks after $pending_max waits ($reason)"
          return 0
        fi
        pending_n=$((pending_n + 1))
        say "batch PR #$bpr: CI has not reported yet; waiting ($pending_n of $pending_max)"
        sleep "$stale_sleep"
      elif [[ $out == *"check that is not passing"* ]]; then
        verdict=red
      else
        stopped="batch PR #$bpr: ${reason:-the CI gate exited $rc}"
        return 0
      fi
    done
    case $verdict in
      green)
        git fetch origin main >/dev/null 2>&1 || { stopped="batch PR #$bpr: could not fetch origin/main before landing it"; return 0; }
        if [[ $(git rev-parse origin/main) != "$b_base" ]]; then
          say "origin/main moved since the batch was built"
          verdict=stale
          reason="origin/main moved"
        # --no-verify: the sha is CI-verified, and .githooks/pre-push checks the working tree, not the pushed sha.
        elif push_out=$(git push --no-verify origin "$sha:refs/heads/main" 2>&1); then
          say "landed batch PR #$bpr: ${sha:0:9} is origin/main"
          open_bpr=
          comment "$bpr" "Landed on main as $sha by a fast-forward push."$'\n\n'"$footer" || say "could not comment on batch PR #$bpr"
          close_pr "$bpr" || true
          delete_remote_branch "$b_branch"
          discard_local_branch "$b_branch"
          finish_originals "$bpr" "${prs[@]}"
          if ! regenerate_roadmap "batch #$bpr"; then
            stopped="batch PR #$bpr is MERGED, but the roadmap regeneration FAILED"
          fi
          return 0
        elif [[ $push_out == *"non-fast-forward"* || $push_out == *"fetch first"* ]]; then
          say "the push of ${sha:0:9} to main was rejected as non-fast-forward (main moved)"
          verdict=stale
          reason="push rejected as non-fast-forward"
        else
          stopped="batch PR #$bpr: pushing ${sha:0:9} to main failed: $push_out"
          return 0
        fi
        ;;
    esac
    case $verdict in
      stale)
        if ((stale_n >= stale_max)); then
          stopped="batch PR #$bpr: base still stale after $stale_max rebuilds (${reason:-merge request failed})"
          return 0
        fi
        stale_n=$((stale_n + 1))
        say "rebuilding on the new main ($stale_n of $stale_max)"
        retire_batch "$bpr" "$b_branch" "Rebuilding on the new main: the base of this batch is stale."
        ;;
      red)
        say "CI is red on batch PR #$bpr (${reason:-no reason read}); splitting ${#prs[@]} PRs"
        retire_batch "$bpr" "$b_branch" "CI is red: splitting this batch in two."
        half=$(((${#prs[@]} + 1) / 2))
        process_group "${prs[@]:0:half}"
        process_group "${prs[@]:half}"
        return 0
        ;;
    esac
  done
}

# --- preflight ---
passing=()
for n in "$@"; do
  say "preflight PR #$n"
  rc=0
  out=$("$merge_pr" --preflight "$n" 2>&1) || rc=$?
  if ((rc == 0)); then
    passing+=("$n")
  else
    [[ -z $out ]] || echo "$out"
    reason=$(grep -m1 -E '^(REFUSED|ERROR):' <<<"$out" || true)
    refused+=("#$n (${reason:-the gate exited $rc})")
  fi
done

if (($# > 1)); then find_chains "$@"; fi
if ((${#passing[@]} > 0)); then
  order_chains "${passing[@]}"
  process_group "${ordered[@]}"
fi

echo "batch: summary"
echo "  merged:  ${merged[*]:-none}"
echo "  dropped: ${dropped[*]:-none}"
echo "  refused: ${refused[*]:-none}"
if [[ -n $stopped ]]; then
  echo "  stopped: $stopped"
  echo "  not attempted: ${not_attempted[*]:-none}"
else
  echo "  stopped: none"
fi
if ((${#dropped[@]} + ${#refused[@]} > 0)) || [[ -n $stopped ]]; then exit 1; fi
